export type Language = "zh" | "en";
export type MessageKey = keyof typeof english;
export interface Message { key: MessageKey; values: Record<string, string | number | Message> }
export type Localized = Message | string;

export function message(key: MessageKey, values: Message["values"] = {}): Message { return { key, values }; }
export function translate(value: Localized, language: Language): string {
  if (typeof value === "string") return value;
  const template = language === "en" ? english[value.key] : value.key;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const replacement = value.values[key];
    return typeof replacement === "object" ? translate(replacement, language) : String(replacement ?? `{${key}}`);
  });
}
export function detectLanguage(languages: readonly string[]): Language {
  return languages[0]?.toLowerCase().startsWith("zh") ? "zh" : "en";
}
export class TransferError extends Error {
  constructor(public detail: Message) { super(translate(detail, "zh")); this.name = "TransferError"; }
}
export function errorDetail(error: unknown, fallback: MessageKey = "操作失败，请重试。"): Message {
  return error instanceof TransferError ? error.detail : message(fallback);
}
